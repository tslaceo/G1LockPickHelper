-- Writes mod/LockPickHelper/Script/LockPickHelper/UnitTests/GoldenSolver.as: the key sequences the 1.2.0 solver (solver.lua,
-- a byte copy of the 1.2.0 file) gives for the locks of locks_data.lua, for the AngelScript solver to reproduce exactly.
-- Run from the repo root with Lua 5.4:  lua tools/oracle/golden.lua
--
-- A case is a lock, how many of its first connections the game drops (Removed), the starting holes of the lock and the
-- cursor; the line is `LPHGolden::Check(T, Db, n"<lock>", <Removed>, <H1>..<H7>, <cursor>, "<keys>");` with the holes
-- plate by plate, front to back (0 for the plates a lock does not have), the cursor 0-based (Lua's 1 is 0) and the keys
-- as letters (W S A D). "-" as the keys means the solver found no safe path.
package.path = "tools/oracle/?.lua;" .. package.path
local solver = require("solver")
local data = dofile("tools/oracle/locks_data.lua")

local OUT_PATH = "mod/LockPickHelper/Script/LockPickHelper/UnitTests/GoldenSolver.as"

local names = {}
local byPlates = {}
for name, lock in pairs(data.locks) do
    names[#names + 1] = name
end
table.sort(names)
for _, name in ipairs(names) do
    local plates = data.locks[name].plates
    byPlates[plates] = byPlates[plates] or {}
    table.insert(byPlates[plates], name)
end

-- The solver's graph of a lock without its first `skip` connections (what lockdb.graph of 1.2.0 did).
local function graph_of(lock, skip)
    local links = {}
    for i = skip + 1, #lock.edges do
        local e = lock.edges[i]
        local list = links[e[1]] or {}
        list[#list + 1] = { e[2], e[3] }
        links[e[1]] = list
    end
    return { plates = lock.plates, links = links }
end

local noSafePath = 0

local function case_line(name, removed, cursor)
    local lock = data.locks[name]
    removed = math.max(0, math.min(#lock.edges, removed))
    local ctx = solver.prepare(graph_of(lock, removed))
    local keys, why = solver.solve(ctx, lock.start, cursor + 1)
    local text
    if keys then
        text = table.concat(keys)
    else
        assert(why == "no_safe_path", name .. ": " .. tostring(why))
        text = "-"
        noSafePath = noSafePath + 1
    end
    local holes = {}
    for i = 1, 7 do holes[i] = lock.start[i] or 0 end
    return string.format('\tLPHGolden::Check(T, Db, n"%s", %d, %s, %d, "%s");', name, removed,
        table.concat(holes, ", "), cursor, text)
end

local function first(plates, count)
    local list = {}
    for i = 1, count do list[i] = byPlates[plates][i] end
    return list
end

-- The quick set: the first four locks (by name) of 4, 5 and 6 plates; two of them again with connections dropped
-- (1 and 2), and three with the cursor away from the first plate (the choice between equal paths looks at the cursor).
local fast = {}
for plates = 4, 6 do
    for _, name in ipairs(first(plates, 4)) do
        fast[#fast + 1] = { name, 0, 0 }
    end
end
fast[#fast + 1] = { byPlates[5][1], 1, 0 }
fast[#fast + 1] = { byPlates[6][1], 2, 0 }
fast[#fast + 1] = { byPlates[4][2], 0, 3 }
fast[#fast + 1] = { byPlates[5][2], 0, 4 }
fast[#fast + 1] = { byPlates[6][2], 1, 2 }

-- The full set: every lock of 4..6 plates with 0, 1 and 2 connections dropped, every 7-plate lock with none dropped.
local full = {}
for plates = 4, 6 do
    for _, name in ipairs(byPlates[plates]) do
        for removed = 0, 2 do
            full[#full + 1] = { name, removed, 0 }
        end
    end
end
for _, name in ipairs(byPlates[7]) do
    full[#full + 1] = { name, 0, 0 }
end

local out = {}
local function add(line) out[#out + 1] = line end

add("// Generated by tools/oracle/golden.lua from the 1.2.0 solver (tools/oracle/solver.lua) and tools/oracle/locks_data.lua")
add("// (" .. data.build .. "). Do not edit by hand. See the first lines of the generator for what a line means.")
add("")

local function emit(title, comment, cases)
    add("// " .. comment)
    add("void " .. title .. "(ULPH_TestRun T)")
    add("{")
    add('\tT.Begin("' .. title:gsub("^LPHTests_", "") .. '");')
    add("\tULPH_LockDb Db = LPHTests_MakeLockDb(T);")
    add("\tLPH_RegisterLockGraphs(Db);")
    for _, c in ipairs(cases) do
        add(case_line(c[1], c[2], c[3]))
    end
    add("}")
    add("")
end

emit("LPHTests_SolverGolden", string.format("The quick set (%d cases): always run.", #fast), fast)
emit("LPHTests_SolverGoldenFull",
    string.format("The full set (%d cases): only with -LPHTests=golden.", #full), full)

local file = assert(io.open(OUT_PATH, "wb"))
file:write(table.concat(out, "\n"))
file:close()
print(string.format("wrote %s: %d quick cases, %d full cases, %d without a safe path", OUT_PATH, #fast, #full, noSafePath))
